import AppKit
import ClipboardCore

final class ClipboardMonitorTests {
    @MainActor func testTextAndScreenshotRoundTripsSuppressOwnWrites() throws {
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        let monitor = ClipboardMonitor(pasteboard: board)
        var captures: [CapturePayload] = []
        monitor.onCapture = { captures.append($0) }
        board.clearContents(); board.setString("Hello 👋\nline two", forType: .string)
        monitor.poll(); monitor.poll()
        expectEqual(captures.count, 1)
        expectTrue(monitor.restore(text: "Earlier text"))
        monitor.poll()
        expectEqual(captures.count, 1)
        expectEqual(board.string(forType: .string), "Earlier text")
        // A later explicit copy of identical text remains a meaningful copy action.
        board.clearContents(); board.setString("Earlier text", forType: .string); monitor.poll()
        expectEqual(captures.count, 2)
        let bitmap = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 20, pixelsHigh: 10, bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)!
        memset(bitmap.bitmapData!, 100, bitmap.bytesPerRow * bitmap.pixelsHigh)
        let png = try unwrap(bitmap.representation(using: .png, properties: [:]))
        board.clearContents(); board.setData(png, forType: .png); board.setData(bitmap.tiffRepresentation, forType: .tiff)
        monitor.poll()
        expectEqual(captures.count, 3)
        guard case .image(let captured) = captures.last else { return fail("Expected one image") }
        expectTrue(monitor.restore(image: captured)); monitor.poll()
        expectEqual(captures.count, 3)
        expectEqual(board.data(forType: .png), png)
        expectNotNil(board.data(forType: .tiff))
        expectEqual(NSImage(pasteboard: board)?.representations.first?.pixelsWide, 20)
    }
    @MainActor func testPauseAndSensitiveMarkers() {
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        let monitor = ClipboardMonitor(pasteboard: board)
        var count = 0; monitor.onCapture = { _ in count += 1 }
        monitor.paused = true
        board.clearContents(); board.setString("paused", forType: .string); monitor.poll()
        monitor.paused = false; monitor.poll()
        expectEqual(count, 0)
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "public.file-url"] {
            board.clearContents(); board.setString("private", forType: .string); board.setData(Data(), forType: NSPasteboard.PasteboardType(marker)); monitor.poll()
        }
        expectEqual(count, 0)
        board.clearContents(); board.setString("ordinary", forType: .string); monitor.poll()
        expectEqual(count, 1)
    }
}
