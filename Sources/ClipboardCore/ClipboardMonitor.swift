import AppKit

@MainActor public final class ClipboardMonitor {
    private let pasteboard: NSPasteboard
    private var tracker: ClipboardChangeTracker
    private var timer: Timer?
    public var paused = false { didSet { tracker.suppress(pasteboard.changeCount) } }
    public var onCapture: ((CapturePayload) -> Void)?
    public init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        tracker = ClipboardChangeTracker(initial: pasteboard.changeCount)
    }
    public func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }
    public func poll() {
        guard tracker.consume(pasteboard.changeCount), !paused else { return }
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        let excluded: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", "public.file-url"]
        guard types.isDisjoint(with: excluded) else { return }
        // Prefer one image representation over the text alternate of the same copy.
        if let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff) { onCapture?(.image(data)) }
        else if let text = pasteboard.string(forType: .string), !text.isEmpty { onCapture?(.text(text)) }
    }
    public func restore(text: String) -> Bool {
        pasteboard.clearContents()
        let ok = pasteboard.setString(text, forType: .string)
        tracker.suppress(pasteboard.changeCount); return ok
    }
    public func restore(image data: Data, tiff: Data? = nil) -> Bool {
        // PNG preserves screenshot transparency. NSImage also supplies TIFF to older destinations.
        guard tiff != nil || NSImage(data: data) != nil else { return false }
        let item = NSPasteboardItem()
        item.setData(data, forType: .png)
        if let tiff = tiff ?? NSImage(data: data)?.tiffRepresentation { item.setData(tiff, forType: .tiff) }
        pasteboard.clearContents()
        let ok = pasteboard.writeObjects([item])
        tracker.suppress(pasteboard.changeCount); return ok
    }
}
